import { test, expect } from '@playwright/test'

// vee-validate compat layer: required / email / min rules, live re-validation, aria wiring (role=alert, aria-invalid, aria-describedby)
test('login form validation', async ({ page }) => {
  await page.route('**/*klaviyo*', (r) => r.abort())
  await page.goto('/auth/login/')
  await page.getByRole('button', { name: /sign in/i }).waitFor({ timeout: 20000 })
  await page.getByRole('button', { name: /sign in/i }).click()
  await page.waitForTimeout(600)
  const alerts = await page.locator('p[role="alert"]').allTextContents()
  console.log('FORM empty submit alerts', JSON.stringify(alerts))
  expect(alerts.length).toBeGreaterThanOrEqual(2)
  const email = page.locator('#loginEmail')
  await expect(email).toHaveAttribute('aria-invalid', 'true')
  await email.fill('not-an-email')
  await page.waitForTimeout(500)
  console.log('FORM invalid email alerts', JSON.stringify(await page.locator('p[role="alert"]').allTextContents()))
  await email.fill('user@example.com')
  await page.waitForTimeout(500)
  const afterValid = await page.locator('#loginEmail-error').count()
  console.log('FORM email error after valid input:', afterValid)
  expect(afterValid).toBe(0)
})

